"""FastAPI application for mlt inference serving.

``create_app`` is the public factory used by both the server subprocess
(server.py) and test code (via TestClient, no subprocess needed).

Endpoints
---------
POST /predict   Run inference on a batch of records.
GET  /schema    Effective input schema for this run.
GET  /metadata  Run identity and summary metrics.
GET  /health    200 when the model is loaded and ready.
"""

from __future__ import annotations

from typing import Any

from fastapi import FastAPI, Request
from fastapi.responses import JSONResponse

from mlt.runstore.manifest import Manifest


BATCH_LIMIT = 1000


# ---------------------------------------------------------------------------
# Schema validation
# ---------------------------------------------------------------------------


def validate_records(records: list[dict], schema: dict) -> list[dict]:
    """Validate *records* against schema features.

    Returns a list of error dicts with keys ``loc`` (e.g. ``inputs[0].age``)
    and ``msg``.  An empty list means all records are valid.
    """
    features = schema.get("features") or {}
    errors: list[dict] = []

    for i, record in enumerate(records):
        for name, spec in features.items():
            value = record.get(name)
            required = spec.get("required", False)

            if value is None:
                if required:
                    errors.append({"loc": f"inputs[{i}].{name}", "msg": "required field"})
                continue

            t = spec.get("type")
            if t == "int" and not isinstance(value, int):
                errors.append({
                    "loc": f"inputs[{i}].{name}",
                    "msg": f"expected int, got {type(value).__name__}",
                })
                continue
            if t == "float" and not isinstance(value, (int, float)):
                errors.append({
                    "loc": f"inputs[{i}].{name}",
                    "msg": f"expected float, got {type(value).__name__}",
                })
                continue
            if t == "str" and not isinstance(value, str):
                errors.append({
                    "loc": f"inputs[{i}].{name}",
                    "msg": f"expected str, got {type(value).__name__}",
                })
                continue

            if "min" in spec and value < spec["min"]:
                errors.append({
                    "loc": f"inputs[{i}].{name}",
                    "msg": f"value {value} below minimum {spec['min']}",
                })
            if "max" in spec and value > spec["max"]:
                errors.append({
                    "loc": f"inputs[{i}].{name}",
                    "msg": f"value {value} above maximum {spec['max']}",
                })
            if "allowed" in spec and value not in spec["allowed"]:
                errors.append({
                    "loc": f"inputs[{i}].{name}",
                    "msg": f"value {value!r} not in allowed: {spec['allowed']}",
                })

    return errors


# ---------------------------------------------------------------------------
# App factory
# ---------------------------------------------------------------------------


def _example_value(spec: dict) -> Any:
    """Return a plausible example value for a schema field spec."""
    if "allowed" in spec:
        return spec["allowed"][0]
    t = spec.get("type", "")
    if t == "int":
        return int(spec.get("min", 0))
    if t == "float":
        return float(spec.get("min", 0.0))
    return ""


def create_app(manifest: Manifest, schema: dict | None, model: Any) -> FastAPI:
    """Create the inference FastAPI app for a single run.

    Parameters
    ----------
    manifest:
        Run metadata used by ``/metadata`` and injected into ``/predict`` responses.
    schema:
        Parsed ``schema_effective.yaml`` dict (``{"features": {...}}``), or ``None``
        to skip validation.
    model:
        Loaded ``MLModel`` instance; must expose ``predict(inputs: list[dict]) -> list``.
        Injected directly so tests can pass a mock without touching the filesystem.
    """
    app = FastAPI(
        title=f"mlt · {manifest.run_id}",
        description="mlt inference API — generated by mlt serve",
        version="1.0",
    )
    app.state.model = model
    app.state.manifest = manifest
    app.state.schema = schema

    @app.get("/health", tags=["ops"])
    def health() -> dict:
        """Return 200 when the model is loaded and ready."""
        return {"status": "ok"}

    # Build a realistic example from the schema so the Swagger "Try it out" is
    # pre-filled with real feature names instead of a generic placeholder.
    if schema and schema.get("features"):
        _example_record = {n: _example_value(s) for n, s in schema["features"].items()}
    else:
        _example_record = {"feature": 0.0}

    @app.post(
        "/predict",
        tags=["inference"],
        openapi_extra={
            "requestBody": {
                "required": True,
                "content": {
                    "application/json": {
                        "schema": {
                            "type": "object",
                            "required": ["inputs"],
                            "properties": {
                                "inputs": {
                                    "type": "array",
                                    "items": {"type": "object"},
                                    "description": "List of feature records.",
                                }
                            },
                        },
                        "example": {"inputs": [_example_record]},
                    }
                },
            }
        },
    )
    async def predict(request: Request) -> JSONResponse:
        """Run inference on a batch of records.

        Body: ``{"inputs": [{"feature": value, …}, …]}``
        """
        # Parse body manually to control error codes (400 / 413 / 422 / 500).
        try:
            body = await request.json()
        except Exception:
            return JSONResponse(status_code=400, content={"detail": "malformed JSON"})

        if not isinstance(body, dict) or "inputs" not in body:
            return JSONResponse(status_code=400, content={"detail": "missing 'inputs' key"})

        inputs = body["inputs"]
        if not isinstance(inputs, list) or len(inputs) == 0:
            return JSONResponse(
                status_code=400,
                content={"detail": "'inputs' must be a non-empty list"},
            )

        if len(inputs) > BATCH_LIMIT:
            return JSONResponse(
                status_code=413,
                content={"detail": f"batch size {len(inputs)} exceeds limit {BATCH_LIMIT}"},
            )

        # Schema validation — only when features are declared.
        if app.state.schema:
            field_errors = validate_records(inputs, app.state.schema)
            if field_errors:
                return JSONResponse(status_code=422, content={"detail": field_errors})

        try:
            predictions = app.state.model.predict(inputs)
        except Exception as exc:  # noqa: BLE001
            # No stack trace in the response (design §11).
            return JSONResponse(
                status_code=500,
                content={"detail": f"predict raised {type(exc).__name__}: {exc}"},
            )

        return JSONResponse(
            content={"predictions": predictions, "run_id": manifest.run_id}
        )

    @app.get("/schema", tags=["ops"])
    def schema_endpoint() -> dict:
        """Return the effective input schema for this run."""
        return app.state.schema or {}

    @app.get("/metadata", tags=["ops"])
    def metadata() -> dict:
        """Return run identity and summary metrics."""
        m = app.state.manifest
        schema_hash = None
        if m.outputs and "schema" in m.outputs:
            schema_hash = m.outputs["schema"].get("hash")
        return {
            "run_id": m.run_id,
            "manifest_version": m.to_dict().get("manifest_version"),
            "fingerprint": m.fingerprint,
            "created_at": m.created_at,
            "metrics": m.metrics,
            "schema_hash": schema_hash,
        }

    return app
